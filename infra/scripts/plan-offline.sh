#!/usr/bin/env bash
# Run fmt-check, validate and a full `terraform plan` for an env WITHOUT any
# real AWS credentials or state bucket.
#
#   infra/scripts/plan-offline.sh [env-dir] [tfvars]
#   defaults:  infra/envs/go-ticketing  example.tfvars
#
# How it works without AWS:
#   1. A temporary *_override.tf file swaps the S3 backend for a local one and
#      sets the provider's skip_* flags, so the provider never calls STS or the
#      EC2 metadata endpoint. Terraform merges override files over the real
#      config, so the committed .tf files contain no test plumbing.
#   2. Fake credentials satisfy the provider's "are there credentials at all"
#      check. They are never sent anywhere that validates them.
#   3. A plan against empty state is all creates, and creates are computed
#      locally — the module avoids data sources that call AWS APIs for exactly
#      this reason (AZs are an input, not a lookup).
#   4. TF_DATA_DIR points at a separate directory, so this never disturbs a real
#      `terraform init` in the same env directory.
set -euo pipefail

TERRAFORM="${TERRAFORM:-terraform}"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
ENV_DIR="$(cd "${1:-$REPO_ROOT/infra/envs/go-ticketing}" && pwd)"
TFVARS="${2:-example.tfvars}"
OVERRIDE="$ENV_DIR/zz_offline_override.tf"

export TF_DATA_DIR="$ENV_DIR/.terraform-offline"
export TF_IN_AUTOMATION=1
export AWS_ACCESS_KEY_ID="AKIAOFFLINEPLANNOTREAL"
export AWS_SECRET_ACCESS_KEY="offline-plan-fake-secret-not-a-real-credential"
unset AWS_PROFILE AWS_SESSION_TOKEN

cleanup() { rm -f "$OVERRIDE"; }
trap cleanup EXIT

cat >"$OVERRIDE" <<EOF
# Generated by infra/scripts/plan-offline.sh — deleted on exit. Never commit.
terraform {
  backend "local" {
    path = "$TF_DATA_DIR/offline.tfstate"
  }
}

provider "aws" {
  skip_credentials_validation = true
  skip_requesting_account_id  = true
  skip_metadata_api_check     = true
  skip_region_validation      = true
}
EOF

echo "==> fmt -check (infra/)"
"$TERRAFORM" fmt -check -recursive "$REPO_ROOT/infra"

cd "$ENV_DIR"

echo "==> init (local backend, $TF_DATA_DIR)"
"$TERRAFORM" init -input=false -reconfigure >/dev/null

echo "==> validate"
"$TERRAFORM" validate

echo "==> plan ($TFVARS, image_tag=offline-plan)"
"$TERRAFORM" plan -input=false -lock=false -refresh=false \
  -var-file="$TFVARS" \
  -var="image_tag=offline-plan" \
  -out="$TF_DATA_DIR/offline.tfplan" | tail -n 25

# Assert the resource graph contains what the deploy and rollback paths depend
# on. A refactor that silently drops one of these should fail here, not in an
# incident.
echo "==> asserting deployment-safety properties of the plan"
"$TERRAFORM" show -json "$TF_DATA_DIR/offline.tfplan" >"$TF_DATA_DIR/plan.json"
"$REPO_ROOT/infra/scripts/check-plan.sh" "$TF_DATA_DIR/plan.json"

# Negative tests: inputs the module must refuse. A guard-rail that silently
# stopped rejecting these would otherwise only be discovered in production.
echo "==> asserting the module rejects unsafe inputs"
expect_rejected() {
  # $1 description, $2 regex the error output must contain, rest: plan args.
  # Matching the message proves the plan failed for the intended reason, not
  # for some unrelated error.
  local description="$1" pattern="$2"; shift 2
  if "$TERRAFORM" plan -input=false -lock=false -refresh=false \
      -var-file="$TFVARS" "$@" >"$TF_DATA_DIR/negative.log" 2>&1; then
    echo "  FAIL  accepted: $description" >&2
    exit 1
  fi
  if ! grep -Eq "$pattern" "$TF_DATA_DIR/negative.log"; then
    echo "  FAIL  rejected for the wrong reason: $description" >&2
    cat "$TF_DATA_DIR/negative.log" >&2
    exit 1
  fi
  echo "  ok    rejects $description"
}
expect_rejected 'image_tag "latest" (would make revisions mutable)' \
  'image_tag must be a valid, immutable' -var='image_tag=latest'
expect_rejected 'a single availability zone' \
  'needs at least two entries' -var='image_tag=x' -var='availability_zones=["eu-west-1a"]'
